from enum import StrEnum


class InternalSquadsMode(StrEnum):
    """Как хост относится к перечисленным внутренним сквадам (панель 3.4.0+).

    До 3.4.0 у хоста был только список ИСКЛЮЧЁННЫХ сквадов
    (``excludedInternalSquads``), то есть режим всегда был ``EXCLUDE``.
    Панель 3.4.0 заменила его на пару «режим + список», добавив обратный
    случай: показывать хост ТОЛЬКО перечисленным сквадам.
    """

    #: Хост скрыт от перечисленных сквадов, виден всем остальным.
    EXCLUDE = "EXCLUDE"
    #: Хост виден ТОЛЬКО перечисленным сквадам. Список обязан быть непустым.
    ALLOW_ONLY = "ALLOW_ONLY"
